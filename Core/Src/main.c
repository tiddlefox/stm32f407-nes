/**
 * main.c - NES emulator on an STM32F407VET6
 *
 * Hardware:
 *   ILI9341 320x240 TFT   SPI1  PA5/PA7 + PB6/PB7/PB8/PB9
 *   microSD (SDIO 4-bit)  PC8..PC12, PD2
 *   Gamepad input         USART1 PA9/PA10  (PC keyboard over USB-TTL)
 *
 * Boot flow:
 *   1. Initialise clocks, GPIO, SPI1 (display) and USART1 (input)
 *   2. Bring up the ILI9341
 *   3. Mount the SD card, find the first *.nes in the root, load it
 *   4. Run the emulator forever
 *
 * The ROM is read into a fixed buffer in CCM — see ROM buffer notes
 * in nes_port.c and the "Known limitations" section of the README.
 */

#include "main.h"
#include "ili9341.h"
#include "uart_pad.h"
#include "sd_card.h"
#include "nes_port.h"
#include "../InfoNES/InfoNES.h"
#include "../InfoNES/InfoNES_System.h"
#include "ff.h"

